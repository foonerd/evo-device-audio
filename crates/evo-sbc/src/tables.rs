#[cfg(test)]
mod tests {
    use super::*;

    /// `true` when `cos((2k + 1)(i + M/2) * pi / (2M))` is exactly zero.
    fn exact_zero(m: usize, i: usize, k: usize) -> bool {
        ((2 * k + 1) * (2 * i + m)) % (4 * m) == 2 * m
    }

    fn cos_rule(m: usize, i: usize, k: usize) -> i32 {
        if exact_zero(m, i, k) {
            return 0;
        }
        let angle = (2 * k + 1) as f64
            * (i as f64 + m as f64 / 2.0)
            * std::f64::consts::PI
            / (2 * m) as f64;
        (angle.cos() * 8192.0).floor() as i32
    }

    #[test]
    fn the_cosine_tables_are_the_rule() {
        for (i, row) in COS_4.iter().enumerate() {
            for (k, &c) in row.iter().enumerate() {
                assert_eq!(c, cos_rule(4, i, k), "COS_4[{i}][{k}]");
            }
        }
        for (i, row) in COS_8.iter().enumerate() {
            for (k, &c) in row.iter().enumerate() {
                assert_eq!(c, cos_rule(8, i, k), "COS_8[{i}][{k}]");
            }
        }
    }

    #[test]
    fn the_window_tables_are_the_rule() {
        for (n, h) in PROTO_4.iter().enumerate() {
            assert_eq!(
                WIN_4[n],
                (-4.0 * h * 32768.0).floor() as i32,
                "WIN_4[{n}]"
            );
        }
        for (n, h) in PROTO_8.iter().enumerate() {
            assert_eq!(
                WIN_8[n],
                (-8.0 * h * 32768.0).floor() as i32,
                "WIN_8[{n}]"
            );
        }
    }

    #[test]
    fn the_zero_rows_are_whole_rows() {
        // Row M/2 of the matrix is the cosine of an odd multiple of pi/2 for
        // every k: the output of that row is always zero.
        assert!(COS_4[2].iter().all(|&c| c == 0));
        assert!(COS_8[4].iter().all(|&c| c == 0));
        assert_eq!(COS_4.iter().flatten().filter(|&&c| c == 0).count(), 4);
        assert_eq!(COS_8.iter().flatten().filter(|&&c| c == 0).count(), 8);
    }

    #[test]
    fn the_prototype_is_a_symmetric_filter() {
        // |h[n]| = |h[L - n]| for the interior of both prototypes.
        for n in 1..40 {
            assert_eq!(PROTO_4[n].abs(), PROTO_4[40 - n].abs(), "PROTO_4[{n}]");
        }
        for n in 1..80 {
            assert_eq!(PROTO_8[n].abs(), PROTO_8[80 - n].abs(), "PROTO_8[{n}]");
        }
    }
}
